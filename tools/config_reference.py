#!/usr/bin/env python3
"""Write docs/config-reference.md, deploy/env.full.example and the application-variable block
of compose.yaml from every Settings class (--check: fail when any is stale). The env file
lists every variable with its doc line: deployment-specific and secret ones carry mock
values, the rest their defaults, and the ones the image or compose already set are commented
out so a copy cannot override them. compose.yaml names every variable the containers read,
because hosting panels hand containers only the variables the compose file names.
Run with the backend venv: backend/.venv/bin/python tools/config_reference.py
"""

import importlib
import pkgutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "config-reference.md"
ENV = ROOT / "deploy" / "env.full.example"
COMPOSE_FILE = ROOT / "compose.yaml"
BLOCK_START = "    # >>> application variables (generated by tools/config_reference.py)\n"
BLOCK_END = "    # <<< application variables\n"
sys.path.insert(0, str(ROOT / "backend" / "src"))

import mindgrid  # noqa: E402
from mindgrid.core import config, config_docs  # noqa: E402

