def discover() -> list[type[config.AppSettings]]:
    for module in pkgutil.walk_packages(mindgrid.__path__, "mindgrid."):
        importlib.import_module(module.name)
    return config.registered()


def _value(name: str, default: object) -> str:
    if name in MOCKS:
        return MOCKS[name]
    if hasattr(default, "get_secret_value"):
        default = default.get_secret_value()  # type: ignore[union-attr]
    if isinstance(default, tuple):
        return ",".join(str(v) for v in default)
    if isinstance(default, bool):
        return str(default).lower()
    return "" if default is None else str(default)


def render_env(classes: list[type[config.AppSettings]]) -> str:
    lines = [
        "# Every variable, generated by tools/config_reference.py (do not edit by hand).",
        "# Copy to deploy/.env (or paste into the hosting panel) and replace every mock value.",
        "# Local run: docker compose --env-file deploy/.env -f compose.yaml \\",
        "#   -f deploy/compose.local.yaml up -d",
        "# Values under a '[mock: replace]' line are fake; the others are the defaults (delete a",
        "# default line to follow future defaults). No inline comments (panels keep them).",
        "",
        "# ---- docker compose ----",
    ]
    for name, (value, doc) in COMPOSE.items():
        lines += [f"# {doc}", f"{name}={value}"]
    client: list[str] = []
    for cls in sorted(classes, key=lambda c: (c.__module__, c.__name__)):
        block = ["", f"# ---- {cls.__name__} ({cls.__module__}) ----"]
        for name, field in config_docs.fields(cls):
            tag = "[mock: replace] " if name in MOCKS else ""
            entry = [f"# {tag}{field.description}"]
            if name in FIXED:
                entry.append(f"# {name}=  ({FIXED[name]})")
            else:
                entry.append(f"{name}={_value(name, field.default)}")
            if name in CLIENT_ONLY:
                client += [f"# {line.lstrip('# ')}" for line in entry]
            else:
                block += entry
        if len(block) > 2:
            lines += block
    lines += ["", "# ---- CLI / MCP client only (a user's machine, not the server) ----", *client]
    return "\n".join(lines) + "\n"


def server_names(classes: list[type[config.AppSettings]]) -> list[str]:
    """Variables the containers read and the image does not set, in a stable order."""
    names = [
        name
        for cls in sorted(classes, key=lambda c: (c.__module__, c.__name__))
        for name, _ in config_docs.fields(cls)
    ]
    return [n for n in names if n not in FIXED and n not in CLIENT_ONLY]


def render_compose(classes: list[type[config.AppSettings]]) -> str:
    """compose.yaml with its application-variable block regenerated."""
    text = COMPOSE_FILE.read_text(encoding="utf-8")
    head, _, rest = text.partition(BLOCK_START)
    _, _, tail = rest.partition(BLOCK_END)
    if not tail:
        sys.exit(f"{COMPOSE_FILE.name}: application-variable markers are missing")
    lines = "".join(f"    {n}: ${{{n}:-}}\n" for n in server_names(classes))
    return head + BLOCK_START + lines + BLOCK_END + tail


def _write_or_check(path: Path, text: str, check: bool) -> bool:
    if check:
        stale = not path.exists() or path.read_text(encoding="utf-8") != text
        print(f"{path.relative_to(ROOT)}: {'stale' if stale else 'current'}")
        return stale
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")
    return False


def main() -> int:
    classes = discover()
    check = "--check" in sys.argv
    stale = _write_or_check(DOC, config_docs.render(classes), check)
    stale |= _write_or_check(ENV, render_env(classes), check)
    stale |= _write_or_check(COMPOSE_FILE, render_compose(classes), check)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
