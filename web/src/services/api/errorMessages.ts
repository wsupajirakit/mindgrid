export const KNOWN_ERROR_CODES = Object.keys(MESSAGES)

export function errorText(error: unknown): string {
  if (!(error instanceof ApiError)) return m.err_network()
  const text = MESSAGES[error.code]
  const params = Object.fromEntries(Object.entries(error.params).map(([k, v]) => [k, String(v)]))
  return text ? text(params) : m.err_generic({ status: String(error.status) })
}
